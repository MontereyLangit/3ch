package ch3s.common.routes

import scala.collection.mutable.ListBuffer

/**
 * `app/routes/配下` を機械生成するためのルートテーブル．
 *
 * TODO: BBS ロジック（dat / subject.txt / bbs.cgi 等）のルートは次タスク以降で追加する。
 * NOTE: 板top→認証画面→bbs.cgi→read.cgi→その他の順で追加予定
 * TODO: `GET /_v6/healthは削除
 */
object RouteTable {
  // Preserve v5 prefix matches (including trailing path characters) and evaluation order.
  val publicPatterns: List[(String, String)] = List(
    "dat" -> "^/([a-zA-Z0-9\\-_]+)/dat/([0-9]{10})\\.dat",
    "subject" -> "^/([a-zA-Z0-9\\-_]+)/subject\\.txt",
    "archive" -> "^/([a-zA-Z0-9\\-_]+)/kako/([0-9]{4})/subject\\.txt",
    "archives" -> "^/([a-zA-Z0-9\\-_]+)/kako/subject\\.txt",
    "head" -> "^/([a-zA-Z0-9\\-_]+)/head\\.txt",
    "settings" -> "^/([a-zA-Z0-9\\-_]+)/SETTING\\.TXT",
    "board" -> "^/([a-zA-Z0-9\\-_]+)/(index\\.html)?$"
  )

  /**
   * `app/islands` 配下の1コンポーネントを route 側（JSX）から参照するための情報
   *
   * @param fileBaseName   `app/islands/<fileBaseName>.tsx` を指す（拡張子無し）
   * @param localVarName   生成route内でこのislandをimportするローカル識別子（JSXタグ名になる）
   */
  final case class IslandRef(fileBaseName: String, localVarName: String)

  /** 生成するrouteファイル形式 */
  enum RouteKind {

    /**
     * `createRoute((c) => exportName(c));` だけの素通しルート
     * `method` が `"GET"`なら `export default`、それ以外は `export const $method =` という named export
     */
    case PassThrough(exportName: String, method: String = "GET")

    /**
     * 1ファイルに複数メソッドを持たせる版
     * `handlers` は `(HTTPメソッド, exportName)` のリスト
     * `"GET"` は `export default`、それ以外は `export const $method =`
     */
    case MultiMethodPassThrough(handlers: List[(String, String)])

    /**
     * `exportName(c, range)` で props を取得し、island へ渡して `c.render` する形
     * `hasRangeParam` が true なら `c.req.param("range")` を渡す（`[range].tsx`）、
     * false なら `undefined` を渡す
     */
    case IslandRender(exportName: String, island: IslandRef, hasRangeParam: Boolean)

    // TODO: 旧main.js>fetch。移行完了後削除
    case LegacyDispatch
  }

  /**
   * ルートエントリ
   * @param filePath `app/routes` からの相対パス（例: `"_v6/health.ts"`）
   *                 HonoXのファイルベースルーティング規約がそのままURLに落とす
   * @param kind      生成するファイルの中身の形
   * @param comment   ファイル冒頭（import群の後）に入れる説明コメント行（1行1要素、`// `込み）
   */
  final case class RouteEntry(filePath: String, kind: RouteKind, comment: List[String])

  /**
   * Client Components用のエントリ
   * @param filePath     `app/islands` からの相対パス（例: `"thread-view.tsx"`）
   * @param exportedName scalajs側が `@JSExportTopLevel` でexportした名前（例: `"ThreadViewJs"`）
   * @param sourceModule import元の仮想モジュール名（例: `"client.js"` → `scalajs:client.js`）
   */
  final case class IslandEntry(filePath: String, exportedName: String, sourceModule: String)

  /**
   * `_middleware.ts`（ディレクトリ単位で適用されるミドルウェア）の生成対象
   * `_middleware.ts` の `default export` は「ミドルウェア関数の配列」という規約
   * （`node_modules/honox/dist/server/server.js` の `middleware.default.map(...)`）
   *
   * @param dirPath           `app/routes` からの相対ディレクトリ（例: `"admin"`）
   * @param exportName        Scala側（`bbs`, `scalajs:server.js`）がexportした関数名。
   *                          シグネチャは `(c) => Promise<Response | undefined>`
   *                          （`undefined` なら通過＝`next()`、`Response` ならそれを即返す＝認可失敗）
   * @param excludePathPrefix 適用対象から除外するパスのprefix
   */
  final case class MiddlewareEntry(dirPath: String, exportName: String, excludePathPrefix: Option[String])

  val routes: List[RouteEntry] = List(
    RouteEntry(
      filePath = "_v6/health.ts",
      kind = RouteKind.PassThrough("healthHandler"),
      comment = List(
        "// GET /_v6/health -- 仮のv6s ビルド骨格の動作確認用エンドポイント（固定文字列を返すだけ）"
      )
    ),
    RouteEntry("index.ts", RouteKind.LegacyDispatch, Nil)
  )

  private val generatedBanner: List[String] = List(
    "// This file is generated by codegen（ch3s.codegen.GenerateAppFiles）from RouteTable.",
    "// Do not edit this file manually. (It will be overwritten every time you run `npm run v6:generate` or `npm run v6:build`.)",
    "// RouteTable: common/src/main/scala/ch3s/common/routes/RouteTable.scala"
  )

  /** `filePath` のディレクトリ部分（末尾のファイル名を除いた部分。ルート直下なら空文字）。 */
  private def directoryOf(filePath: String): String = {
    val idx = filePath.lastIndexOf('/')
    if (idx < 0) "" else filePath.substring(0, idx)
  }

  /**
   * このファイルから `app/islands/` へ辿るための `../` の個数
   * `app/routes` から見た `filePath` のディレクトリ階層数 + 1（`routes` ディレクトリ自体を抜ける分）
   */
  private def upsToAppRoot(filePath: String): String = {
    val dir = directoryOf(filePath)
    val segments = if (dir.isEmpty) 0 else dir.count(_ == '/') + 1
    "../" * (segments + 1)
  }

  /** island コンポーネントへの相対importパス（`app/islands/<fileBaseName>` を指す） */
  def islandImportPath(filePath: String, islandFileBaseName: String): String = {
    s"${upsToAppRoot(filePath)}islands/$islandFileBaseName"
  }

  /** [[RouteKind.PassThrough]] の1メソッド分の export 行を生成する */
  private def methodExportLine(method: String, exportName: String): String = {
    if (method == "GET") s"export default createRoute((c) => $exportName(c));"
    else s"""export const $method = createRoute((c) => $exportName(c));"""
  }

  /** 
   * RouteFileを生成する
   * @param entry ルートエントリ
   * @return 生成物
   */
  def renderRouteFile(entry: RouteEntry): String = {
    val lines = ListBuffer.empty[String]
    lines ++= generatedBanner
    lines += "import { createRoute } from \"honox/factory\";"

    entry.kind match {
      case RouteTable.RouteKind.LegacyDispatch =>
        lines += "import { createHono } from \"honox/factory\";"
        lines += "// @ts-expect-error scalajs:server.js is resolved by the Scala.js Vite plugin."
        lines += "import { publicHandler, healthHandler } from \"scalajs:server.js\";"
        lines += "const app = createHono();"
        lines += "app.all('*', (c) => c.req.path === '/_v6/health' ? healthHandler(c) : publicHandler(c));"
        lines += "export default app;"
      case RouteTable.RouteKind.PassThrough(exportName, method) =>
        lines += "// @ts-expect-error scalajs:server.js は仮想モジュール（vite.config.ts参照）。"
        lines += s"""import { $exportName } from "scalajs:server.js";"""
        lines += ""
        lines ++= entry.comment
        lines += methodExportLine(method, exportName)
      case RouteTable.RouteKind.MultiMethodPassThrough(handlers) =>
        val exportNames = handlers.map(_._2).distinct
        lines += "// @ts-expect-error scalajs:server.js は仮想モジュール（vite.config.ts参照）。"
        lines += s"""import { ${exportNames.mkString(", ")} } from "scalajs:server.js";"""
        lines += ""
        lines ++= entry.comment
        for ((method, exportName) <- handlers) lines += methodExportLine(method, exportName)

      case RouteTable.RouteKind.IslandRender(exportName, island, hasRangeParam) =>
        lines += s"""import ${island.localVarName} from "${islandImportPath(entry.filePath, island.fileBaseName)}";"""
        lines += "// @ts-expect-error scalajs:server.js は仮想モジュール（vite.config.ts参照）。"
        lines += s"""import { $exportName } from "scalajs:server.js";"""
        lines += ""
        lines ++= entry.comment
        lines += "export default createRoute(async (c) => {"
        val rangeArg = if (hasRangeParam) """c.req.param("range")""" else "undefined"
        lines += s"  const props = await $exportName(c, $rangeArg);"
        lines += "  if (!props) return c.notFound();"
        lines += s"  return c.render(<${island.localVarName} {...props} />, { title: props.title });"
        lines += "});"
    }

    lines.mkString("\n") + "\n"
  }

  /**
   * islandFileを生成する
   * @param entry アイランドエントリ
   * @return 生成物
   */
  def renderIslandFile(entry: IslandEntry): String = {
    val lines = ListBuffer.empty[String]
    lines ++= generatedBanner
    lines += s"""// @ts-expect-error scalajs:${entry.sourceModule} は @scala-js/vite-plugin-scalajs が解決する仮想モジュール（.d.ts無し）。"""
    lines += s"""import { ${entry.exportedName} } from "scalajs:${entry.sourceModule}";"""
    lines += s"export default ${entry.exportedName};"
    lines.mkString("\n") + "\n"
  }

  /**
   * `_middleware.ts` 1件分のファイル内容を生成する
   * `createMiddleware`（`hono/factory`）は型推論の補助にすぎず実行時に必須ではないため入れない
   * プレーン関数を配列に入れ default export する
   */
  def renderMiddlewareFile(entry: MiddlewareEntry): String = {
    val lines = ListBuffer.empty[String]
    lines ++= generatedBanner
    lines += "// @ts-expect-error scalajs:server.js は仮想モジュール（vite.config.ts参照）。"
    lines += s"""import { ${entry.exportName} } from "scalajs:server.js";"""
    lines += ""
    lines += "export default ["
    lines += "  async (c, next) => {"
    entry.excludePathPrefix.foreach { prefix =>
      lines += s"""    if (c.req.path.startsWith("$prefix")) return next();"""
    }
    lines += s"    const blocked = await ${entry.exportName}(c);"
    lines += "    if (blocked) return blocked;"
    lines += "    return next();"
    lines += "  },"
    lines += "];"
    lines.mkString("\n") + "\n"
  }

}
