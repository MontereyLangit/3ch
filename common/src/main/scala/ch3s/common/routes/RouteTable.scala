package ch3s.common.routes

import scala.collection.mutable.ListBuffer

/** Public compatibility patterns and annotation-derived entry rendering. */
object RouteTable {

  // Preserve v5 prefix matches (including trailing path characters) and evaluation order.
  val publicPatterns: List[(String, String)] = List(
    "dat" -> "^/([a-zA-Z0-9\\-_]+)/dat/([0-9]{10})\\.dat",
    "subject" -> "^/([a-zA-Z0-9\\-_]+)/subject\\.txt",
    "archive" -> "^/([a-zA-Z0-9\\-_]+)/kako/([0-9]{4})/subject\\.txt",
    "archives" -> "^/([a-zA-Z0-9\\-_]+)/kako/subject\\.txt",
    "head" -> "^/([a-zA-Z0-9\\-_]+)/head\\.txt",
    "settings" -> "^/([a-zA-Z0-9\\-_]+)/SETTING\\.TXT",
    "board" -> "^/([a-zA-Z0-9\\-_]+)/(index\\.html)?$"
  )


  /** 生成するrouteファイル形式 */
  enum RouteKind {

    /**
     * `createRoute((c) => exportName(c));` だけの素通しルート
     * `method` が `"GET"`なら `export default`、それ以外は `export const $method =` という named export
     */
    case PassThrough(exportName: String, method: String = "GET")

    /**
     * 1ファイルに複数メソッドを持たせる版
     * `handlers` は `(HTTPメソッド, exportName)` のリスト
     * `"GET"` は `export default`、それ以外は `export const $method =`
     */
    case MultiMethodPassThrough(handlers: List[(String, String)])

  }

  /**
   * ルートエントリ
   * @param filePath `app/routes` からの相対パス（例: `"_v6/health.ts"`）
   *                 HonoXのファイルベースルーティング規約がそのままURLに落とす
   * @param kind      生成するファイルの中身の形
   * @param comment   ファイル冒頭（import群の後）に入れる説明コメント行（1行1要素、`// `込み）
   */
  final case class RouteEntry(filePath: String, kind: RouteKind, comment: List[String])

  /**
   * Islands Components用のエントリ
   * @param filePath     `app/islands` からの相対パス（例: `"thread-view.tsx"`）
   * @param exportedName scalajs側が `@JSExportTopLevel` でexportした名前（例: `"ThreadViewJs"`）
   * @param sourceModule import元の仮想モジュール名（例: `"client.js"` → `scalajs:client.js`）
   */
  final case class IslandEntry(filePath: String, exportedName: String, sourceModule: String)

  private val generatedBanner: List[String] = List(
    "// This file is generated by codegen（ch3s.codegen.GenerateAppFiles）from @route / @islands.",
    "// Do not edit this file manually. (It will be overwritten every time you run `npm run v6:generate` or `npm run v6:build`.)",
    "// Sources: bbs/Main.scala and bbs-client/Main.scala"
  )

  /** [[RouteKind.PassThrough]] の1メソッド分の export 行を生成する */
  private def methodExportLine(method: String, exportName: String): String = {
    if (method == "GET") s"export default createRoute((c) => $exportName(c));"
    else s"""export const $method = createRoute((c) => $exportName(c));"""
  }

  /** 
   * RouteFileを生成する
   * @param entry ルートエントリ
   * @return 生成物
   */
  def renderRouteFile(entry: RouteEntry): String = {
    val lines = ListBuffer.empty[String]
    lines ++= generatedBanner
    lines += "import { createRoute } from \"honox/factory\";"

    entry.kind match {
      case RouteTable.RouteKind.PassThrough(exportName, method) =>
        lines += "// @ts-expect-error scalajs:server.js は仮想モジュール（vite.config.ts参照）。"
        lines += s"""import { $exportName } from "scalajs:server.js";"""
        lines += ""
        lines ++= entry.comment
        lines += methodExportLine(method, exportName)
      case RouteTable.RouteKind.MultiMethodPassThrough(handlers) =>
        val exportNames = handlers.map(_._2).distinct
        lines += "// @ts-expect-error scalajs:server.js は仮想モジュール（vite.config.ts参照）。"
        lines += s"""import { ${exportNames.mkString(", ")} } from "scalajs:server.js";"""
        lines += ""
        lines ++= entry.comment
        for ((method, exportName) <- handlers) lines += methodExportLine(method, exportName)
    }

    lines.mkString("\n") + "\n"
  }

  /**
   * islandFileを生成する
   * @param entry アイランドエントリ
   * @return 生成物
   */
  def renderIslandFile(entry: IslandEntry): String = {
    val lines = ListBuffer.empty[String]
    lines ++= generatedBanner
    lines += s"""// @ts-expect-error scalajs:${entry.sourceModule} は @scala-js/vite-plugin-scalajs が解決する仮想モジュール（.d.ts無し）。"""
    lines += s"""import { ${entry.exportedName} } from "scalajs:${entry.sourceModule}";"""
    lines += s"export default ${entry.exportedName};"
    lines.mkString("\n") + "\n"
  }

}
