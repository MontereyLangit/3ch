package io._3ch.codegen

import io._3ch.codegen.framework.{Codegen, CodegenConfig, CodegenFailure, OutputWriter}
import io._3ch.codegen.framework.CodegenReport.exitOnError

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path, Paths}

/**
 * 3ch の設定で配線を生成する。引数が無ければ route / island の TS ファイルと DO の TS 型（sbt codegen/run）
 * `--island-components <出力ファイル>` なら SSR 用 Scala API だけ（bbs の sourceGenerators）。`--project-root` を省くとカレントディレクトリ
 */
object GenerateAppFiles {

  def config(projectRoot: Path, scalaOutput: Option[Path] = None): CodegenConfig = CodegenConfig(
    projectRoot = projectRoot,
    serverSources = List("bbs/src/main/scala/io/_3ch/bbs/Main.scala"),
    clientSources = List("bbs-client/src/main/scala/io/_3ch/bbsclient/Main.scala"),
    serverModule = "server",
    clientModule = "client",
    routeDir = "app/routes",
    islandDir = "app/islands",
    islandIdPrefix = "/app/islands/",
    scalaOutput = scalaOutput,
    scalaPackage = "io._3ch.bbs.generated",
    scalaObject = "IslandComponents",
    islandBridge = "io._3ch.bbs.external.honox.Island",
    annotationPackage = "io._3ch.common.routes",
    virtualModulePrefix = "scalajs:",
    banner = List(
      "// This file is generated by codegen（io._3ch.codegen.GenerateAppFiles）from @route / @islands.",
      "// Do not edit this file manually. (It will be overwritten every time you run `npm run v6:generate` or `npm run v6:build`.)",
      "// Sources: bbs/Main.scala and bbs-client/Main.scala"
    ),
    generatedMarker = "// This file is generated by codegen"
  )

  /** 以前 sbt の管理外に出していた SSR 用 Scala API。残っていると src_managed の生成物と重複する */
  private val legacyIslandComponents = "bbs/src/main/scala/io/_3ch/bbs/generated/IslandComponents.scala"

  def main(args: Array[String]): Unit = {
    val (projectRoot, rest) = args.toList match {
      case "--project-root" :: root :: tail => (Paths.get(root).toAbsolutePath.normalize(), tail)
      case other => (Paths.get(System.getProperty("user.dir")).toAbsolutePath, other)
    }
    removeLegacyIslandComponents(projectRoot)
    rest match {
      case Nil =>
        exitOnError(Codegen.appFiles(config(projectRoot)), "route / island files")
        val durableRoot = projectRoot.resolve("bbs/src/main/scala/io/_3ch/bbs/durable")
        val types = projectRoot.resolve("app/scalajs-durable-objects.generated.d.ts")
        val changed = OutputWriter.writeIfChanged(types, GenerateDurableObjectTypes.render(DurableObjectSources.read(durableRoot)))
        println(s"[codegen] Durable Object types: ${if (changed) "wrote" else "unchanged"} $types")
      case List("--island-components", output) =>
        exitOnError(Codegen.islandComponents(config(projectRoot, Some(Paths.get(output)))), "island components")
      case _ =>
        throw new CodegenFailure("usage: GenerateAppFiles [--project-root <dir>] [--island-components <output file>]")
    }
  }

  private def removeLegacyIslandComponents(projectRoot: Path): Unit = {
    val legacy = projectRoot.resolve(legacyIslandComponents)
    if (Files.isRegularFile(legacy) && Files.readString(legacy, StandardCharsets.UTF_8).startsWith(config(projectRoot).generatedMarker)) {
      Files.delete(legacy)
      println(s"[codegen] deleted legacy $legacy")
    }
  }

}
