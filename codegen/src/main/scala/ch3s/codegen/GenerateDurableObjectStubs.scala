package ch3s.codegen

import scala.meta.*

/**
 * DO クラスの公開メソッドから `@js.native` の RPC スタブ（`BoardDoStub` 等）を生成する。
 * 対応範囲・拒否条件は docs/durable-object-stubs.md を参照。
 */
object GenerateDurableObjectStubs {
  val packageName = "ch3s.bbs.external.cloudflare"
  private val primitives = Set("String", "Boolean", "Int", "Double", "Unit")
  // scala / Predef 由来で RPC 境界に向かない型。`*` import 経由の facade と誤解されないよう明示的に拒否する
  private val rejectedScalaTypes = Set(
    "Long", "Float", "Short", "Byte", "Char", "Any", "AnyRef", "AnyVal", "Nothing", "Null",
    "Option", "Some", "None", "Seq", "List", "Vector", "Array", "Map", "Set", "Either", "Future"
  )
  private val jsPromise = Set("js.Promise", "scala.scalajs.js.Promise")
  private val jsUndefOr = Set("js.UndefOr", "scala.scalajs.js.UndefOr")

  /** export 名から Stub 名を決める（`Board` → `BoardDoStub`、`V6PlaceholderDurableObject` → `V6PlaceholderDoStub`）。 */
  def stubName(exportName: String): String = identifier(exportName.stripSuffix("DurableObject") + "DoStub")

  def render(sources: Seq[(String, String)]): String = {
    val parsed = sources.map { case (path, source) => path -> DurableObjectSources.parse(path, source) }
    val localNames = parsed.flatMap { case (_, tree) =>
      tree.collect {
        case d: Defn.Class => d.name.value
        case d: Defn.Trait => d.name.value
        case d: Defn.Object => d.name.value
        case d: Defn.Type => d.name.value
        case d: Defn.Enum => d.name.value
      }
    }.toSet
    val stubs = parsed.flatMap { case (path, tree) =>
      val importers = tree.collect { case i: Import => i }.flatMap(_.importers)
      DurableObjectSources.serverExports(path, tree).map { case (exportName, cls) =>
        exportName -> renderStub(new Scope(path, importers, localNames), exportName, cls)
      }
    }.sortBy(_._1)
    val names = stubs.map(_._1)
    require(names.distinct.size == names.size, s"Duplicate Durable Object export names: ${names.diff(names.distinct).distinct.mkString(", ")}")
    "// Generated by bbs/Compile/sourceGenerators (ch3s.codegen.GenerateDurableObjectStubs) from the\n" +
      "// public methods of the Durable Object classes under bbs/src/main/scala/ch3s/bbs/durable. Do not edit.\n" +
      s"package $packageName\n\nimport scala.scalajs.js\n" + stubs.map(_._2).mkString
  }

  private def renderStub(scope: Scope, exportName: String, cls: Defn.Class): String = {
    val className = cls.name.value
    val methods = cls.templ.body.stats.flatMap {
      case d: Defn.Def if isPrivate(d.mods) => None
      case d: Defn.Def if isProtected(d.mods) =>
        scope.fail(s"$className.${d.name.value}", "protected methods are exposed to JS by Scala.js but are not supported; make it public or private")
      case d: Defn.Def => Some(renderMethod(scope, cls, d))
      case d: Decl.Def if !isPrivate(d.mods) => scope.fail(s"$className.${d.name.value}", "abstract methods are not supported")
      case d: Defn.ExtensionGroup => scope.fail(className, "extension methods are not supported")
      case d: Defn.Given => scope.fail(className, s"given ${d.name.syntax} is not supported")
      case d: Defn.GivenAlias => scope.fail(className, s"given ${d.name.syntax} is not supported")
      case d: Defn.Class if !isPrivate(d.mods) => scope.fail(s"$className.${d.name.value}", "nested public classes are not supported")
      case d: Defn.Trait if !isPrivate(d.mods) => scope.fail(s"$className.${d.name.value}", "nested public traits are not supported")
      case d: Defn.Object if !isPrivate(d.mods) => scope.fail(s"$className.${d.name.value}", "nested public objects are not supported")
      case d: Defn.Enum if !isPrivate(d.mods) => scope.fail(s"$className.${d.name.value}", "nested public enums are not supported")
      case d: Defn.Type if !isPrivate(d.mods) => scope.fail(s"$className.${d.name.value}", "public type aliases are not supported")
      case _ => None // フィールド（val / var）、private な宣言、副コンストラクタ、式
    }.sortBy(_._1)
    val names = methods.map(_._1)
    require(names.distinct.size == names.size,
      s"${scope.path}: ${cls.name.value}: overloaded methods are not supported: ${names.diff(names.distinct).distinct.mkString(", ")}")
    val source = if exportName == className then "" else s"（$className）"
    s"\n/** `$exportName`$source の RPC スタブ。 */\n@js.native\ntrait ${stubName(exportName)} extends DurableObjectStub {\n" +
      methods.map(_._2).mkString + "}\n"
  }

  private def isPrivate(mods: List[Mod]): Boolean = mods.exists(_.is[Mod.Private])
  private def isProtected(mods: List[Mod]): Boolean = mods.exists(_.is[Mod.Protected])

  private def renderMethod(scope: Scope, cls: Defn.Class, d: Defn.Def): (String, String) = {
    val member = s"${cls.name.value}.${d.name.value}"
    val name = scope.identifier(member, d.name.syntax)
    d.mods.foreach {
      case _: Mod.Annot => scope.fail(member, "annotated methods (@JSName etc.) are not supported")
      case _: Mod.Inline | _: Mod.Implicit | _: Mod.Transparent => scope.fail(member, s"modifier is not supported")
      case _ => ()
    }
    val clause = d.paramClauseGroups match {
      case List(group) =>
        if group.tparamClause.values.nonEmpty then scope.fail(member, "type parameters are not supported")
        group.paramClauses match {
          case List(clause) => clause
          case _ => scope.fail(member, "exactly one parameter list is required")
        }
      case Nil => scope.fail(member, "a parameter list `()` is required (a parameterless def is a JS property, not an RPC method)")
      case _ => scope.fail(member, "multiple parameter lists are not supported")
    }
    if clause.mod.isDefined then scope.fail(member, "implicit / using parameters are not supported")
    val params = clause.values.map { param =>
      param.mods.foreach {
        case _: Mod.Annot => scope.fail(member, "annotated parameters are not supported")
        case _: Mod.Inline | _: Mod.Implicit => scope.fail(member, "parameter modifiers are not supported")
        case _ => ()
      }
      val tpe = param.decltpe.getOrElse(scope.fail(member, s"parameter ${param.name.value} needs an explicit type"))
      tpe match {
        case _: Type.Repeated => scope.fail(member, "varargs are not supported")
        case _: Type.ByName => scope.fail(member, "by-name parameters are not supported")
        case _ => ()
      }
      val rendered = scope.render(member, tpe)
      val name = scope.identifier(member, param.name.syntax)
      if param.default.isDefined then {
        val optional = if isApplication(tpe, jsUndefOr) then rendered else s"js.UndefOr[$rendered]"
        s"$name: $optional = js.native"
      } else s"$name: $rendered"
    }
    val result = d.decltpe.getOrElse(scope.fail(member, "an explicit return type is required")) match {
      case t: Type.Apply if isApplication(t, jsPromise) && t.argClause.values.size == 1 =>
        s"js.Promise[${scope.render(member, t.argClause.values.head)}]"
      case other => scope.fail(member, s"return type must be js.Promise[T], found ${other.syntax}")
    }
    d.name.value -> s"  def $name(${params.mkString(", ")}): $result = js.native\n"
  }

  private def isApplication(tpe: Type, constructors: Set[String]): Boolean = tpe match {
    case t: Type.Apply => constructors(t.tpe.syntax)
    case _ => false
  }

  private val identifierPattern = "[A-Za-z_][A-Za-z0-9_]*"

  private def identifier(name: String): String = {
    require(name.matches(identifierPattern), s"Unsupported identifier: $name")
    name
  }

  /** 1 ファイル分の import から、シグネチャに現れる型名を生成先で解決できる形へ写す。 */
  private final class Scope(val path: String, importers: List[Importer], localNames: Set[String]) {
    private val importsJs = importers.exists { importer =>
      importer.ref.syntax == "scala.scalajs" && importer.importees.exists {
        case Importee.Name(name) => name.value == "js"
        case _ => false
      }
    }

    def fail(member: String, message: String): Nothing =
      throw new IllegalArgumentException(s"$path: $member: $message")

    /** backquote 付きの名前（`` `type` `` 等）は `syntax` に backquote が残るので拒否される。 */
    def identifier(member: String, name: String): String =
      if name.matches(identifierPattern) then name else fail(member, s"unsupported identifier $name")

    def render(member: String, tpe: Type): String = tpe match {
      case Type.Name(name) if primitives(name) => name
      case Type.Name(name) if rejectedScalaTypes(name) =>
        fail(member, s"type $name cannot cross the RPC boundary; use js.* types or String/Boolean/Int/Double/Unit")
      case Type.Name(name) => s"$packageName.${resolveSimple(member, name)}"
      case t: Type.Select =>
        root(member, t.qual) match {
          case "js" =>
            if !importsJs then fail(member, s"${t.syntax} requires `import scala.scalajs.js`")
            t.syntax
          case "scala" if t.qual.syntax.startsWith("scala.scalajs.js") => t.syntax
          case "ch3s" if t.qual.syntax == packageName => t.syntax
          case _ => fail(member, s"unsupported qualified type ${t.syntax}: only js.*, scala.scalajs.js.* and $packageName.* are allowed")
        }
      case t: Type.Apply =>
        s"${render(member, t.tpe)}[${t.argClause.values.map(render(member, _)).mkString(", ")}]"
      case other => fail(member, s"unsupported type syntax ${other.syntax}")
    }

    private def root(member: String, ref: Term): String = ref match {
      case Term.Name(name) => name
      case Term.Select(qual, _) => root(member, qual)
      case other => fail(member, s"unsupported type qualifier ${other.syntax}")
    }

    /** 単純名は `packageName` からの import（明示または `*`）で来たものだけ受け付ける。 */
    private def resolveSimple(member: String, name: String): String = {
      if localNames(name) then fail(member, s"type $name is declared in the Durable Object sources; RPC signatures may only use js.* and $packageName facades")
      val explicit = importers.filter(_.importees.exists {
        case Importee.Name(n) => n.value == name
        case Importee.Rename(_, rename) if rename.value == name => fail(member, s"type $name comes from a renaming import, which is not supported")
        case _ => false
      })
      val wildcard = importers.filter { importer =>
        importer.importees.exists(_.is[Importee.Wildcard]) && !importer.importees.exists {
          case Importee.Unimport(n) => n.value == name
          case _ => false
        }
      }
      val candidates = (if explicit.nonEmpty then explicit else wildcard).map(_.ref.syntax).distinct
      candidates match {
        case List(`packageName`) => name
        case Nil => fail(member, s"type $name is not imported; RPC signatures may only use js.*, String/Boolean/Int/Double/Unit and $packageName facades")
        case refs if explicit.nonEmpty => fail(member, s"type $name is imported from ${refs.mkString(", ")}, but only $packageName facades are allowed")
        case refs if refs.contains(packageName) => name
        case refs => fail(member, s"type $name would come from a wildcard import of ${refs.mkString(", ")}, but only $packageName facades are allowed")
      }
    }
  }
}
