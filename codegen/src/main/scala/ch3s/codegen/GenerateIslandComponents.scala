package ch3s.codegen

import ch3s.common.routes.RouteTable.IslandEntry

/** @islands のクライアント export とファイル識別子を SSR 用 Scala API に結び付ける。 */
object GenerateIslandComponents {
  def render(entries: List[IslandEntry]): String = {
    require(entries.map(_.exportedName).distinct.size == entries.size, "duplicate island export name")
    val header = """// This file is generated by codegen（ch3s.codegen.GenerateAppFiles）from @islands.
                   |// Do not edit this file manually.
                   |package ch3s.bbs.generated
                   |""".stripMargin
    if (entries.isEmpty) {
      header + "\nobject IslandComponents {}\n"
    } else {
      val imports = """
                      |import japgolly.scalajs.react.facade.{HasMutableDisplayName, React}
                      |import scala.scalajs.js
                      |import scala.scalajs.js.annotation.JSImport
                      |""".stripMargin
      val components = entries.zipWithIndex.map { case (entry, index) =>
        s"""
           |@js.native
           |@JSImport("scalajs:${entry.sourceModule}", "${entry.exportedName}")
           |private object IslandComponent$index extends js.Function1[js.Object, React.Node] with HasMutableDisplayName {
           |  def apply(props: js.Object): React.Node = js.native
           |}
           |""".stripMargin
      }.mkString
      val methods = entries.zipWithIndex.map { case (entry, index) =>
        s"""  def `${entry.exportedName}`(props: _root_.scala.scalajs.js.Object): _root_.japgolly.scalajs.react.vdom.VdomElement = {
           |    _root_.ch3s.bbs.external.honox.Island(_root_.ch3s.bbs.generated.IslandComponent$index, props, "/app/islands/${entry.filePath}")
           |  }
           |
           |""".stripMargin
      }.mkString
      header + imports + components + "\nobject IslandComponents {\n" + methods + "}\n"
    }
  }
}
