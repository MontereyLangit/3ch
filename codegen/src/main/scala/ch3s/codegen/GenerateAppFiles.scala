package ch3s.codegen

import ch3s.common.routes.RouteTable

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path, Paths}
import scala.jdk.CollectionConverters.*

/** 
 * Main のアノテーションからルートと islands、DO の Scala 宣言から TS 型を生成する。
 * リポジトリルートで `sbt codegen/run` を実行する。
 */
object GenerateAppFiles {

  def main(args: Array[String]): Unit = {
    val projectRoot = Paths.get(System.getProperty("user.dir")).toAbsolutePath
    val appRoot = projectRoot.resolve("app")
    val durableRoot = projectRoot.resolve("bbs/src/main/scala/ch3s/bbs/durable")
    val files = Files.walk(durableRoot)
    val sources = try {
      files.iterator().asScala.filter(_.toString.endsWith(".scala")).toList.sortBy(_.toString).map { path =>
        path.toString -> Files.readString(path, StandardCharsets.UTF_8)
      }
    } finally {
      files.close()
    }
    writeFile(appRoot.resolve("scalajs-durable-objects.generated.d.ts"), GenerateDurableObjectTypes.render(sources))

    def entries(relativePath: String, module: String): AnnotatedAppEntries.Entries = {
      val path = projectRoot.resolve(relativePath)
      AnnotatedAppEntries.parse(relativePath, Files.readString(path, StandardCharsets.UTF_8), module)
    }
    val server = entries("bbs/src/main/scala/ch3s/bbs/Main.scala", "server")
    val client = entries("bbs-client/src/main/scala/ch3s/bbsclient/Main.scala", "client")
    val islandComponents = GenerateIslandComponents.render(client.islands)
    val outputs = server.routes.map(entry => resolveUnderApp(appRoot, "routes", entry.filePath) -> RouteTable.renderRouteFile(entry)) ++
      client.islands.map(entry => resolveUnderApp(appRoot, "islands", entry.filePath) -> RouteTable.renderIslandFile(entry)) :+
      (projectRoot.resolve("bbs/src/main/scala/ch3s/bbs/generated/IslandComponents.scala") -> islandComponents)
    writeOutputs(appRoot, outputs)
    println(s"[codegen] Main annotations: ${server.routes.size} route files, ${client.islands.size} island files")
  }

  private[codegen] def writeOutputs(appRoot: Path, outputs: List[(Path, String)]): Unit = {
    outputs.foreach { case (path, _) =>
      require(!Files.exists(path) || isGenerated(path), s"Refusing to overwrite handwritten file: $path")
    }
    List("routes", "islands").foreach { directory =>
      val root = appRoot.resolve(directory)
      if (Files.isDirectory(root)) {
        val existing = Files.walk(root)
        try {
          existing.iterator().asScala.filter(path => Files.isRegularFile(path) && !Files.isSymbolicLink(path)).foreach { path =>
            if (!outputs.exists(_._1 == path) && isGenerated(path)) Files.delete(path)
          }
        } finally { existing.close() }
      }
    }
    outputs.foreach { case (path, content) => writeFile(path, content) }
  }

  /** `"_v6/health.ts"` のような `/` 区切りの相対パスを `appRoot/subDir/...` へ安全に解決する。 */
  private def resolveUnderApp(appRoot: Path, subDir: String, relativeSlashPath: String): Path = {
    relativeSlashPath.split("/").foldLeft(appRoot.resolve(subDir))((acc, segment) => acc.resolve(segment))
  }

  private def writeFile(path: Path, content: String): Unit = {
    Files.createDirectories(path.getParent)
    Files.write(path, content.getBytes(StandardCharsets.UTF_8))
    println(s"[codegen] wrote ${path.toString}")
  }

  private def isGenerated(path: Path): Boolean = {
    val name = path.getFileName.toString
    (name.endsWith(".ts") || name.endsWith(".tsx") || name.endsWith(".scala")) &&
      Files.readString(path, StandardCharsets.UTF_8).startsWith("// This file is generated by codegen（ch3s.codegen.GenerateAppFiles）")
  }
}
