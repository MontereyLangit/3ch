package io._3ch.codegen

class GenerateDurableObjectStubsSuite extends munit.FunSuite {
  private val prelude =
    """package io._3ch.bbs.durable
      |import io._3ch.bbs.external.cloudflare.*
      |import scala.scalajs.js
      |import scala.scalajs.js.annotation.JSExportTopLevel
      |""".stripMargin

  private def render(body: String, name: String = "Board", exportName: String = "Board", header: String = prelude): String =
    GenerateDurableObjectStubs.render(Seq("Example.scala" -> (header +
      s"""@JSExportTopLevel("$exportName", "server")
         |class $name(val state: DurableObjectState, env: js.Any) extends DurableObject(state, env) {
         |$body
         |}
         |""".stripMargin)))

  private def rejects(body: String, header: String = prelude): String =
    intercept[IllegalArgumentException](render(body, header = header)).getMessage

  test("public methods become js.native members of a stub named after the export; private members, fields and nested defs are skipped") {
    val result = render(
      """  private def read(key: String): js.Promise[String] = js.native
        |  private[durable] def scoped(): js.Promise[Unit] = js.native
        |  private object Helpers { def helper(): js.Promise[Unit] = js.native }
        |  val size: Int = 1
        |  var count: Int = 0
        |  // def commented(): js.Promise[Unit] = js.native
        |  val text = "def quoted(): js.Promise[Unit]"
        |  def getSubject(): js.Promise[String] = {
        |    def nested(): js.Promise[Unit] = js.native
        |    nested(); js.native
        |  }
        |  override def removeThread(key: String, limit: js.Dynamic): js.Promise[js.Array[String]] = js.native
        |  final def getRemoved(): js.Promise[js.Array[String]] = js.native
        |""".stripMargin)
    assert(result.startsWith("// Generated by"))
    assert(result.contains("package io._3ch.bbs.external.cloudflare\n\nimport scala.scalajs.js\n"))
    assert(result.contains("@js.native\ntrait BoardDoStub extends DurableObjectStub {\n"))
    assert(result.contains("  def getSubject(): js.Promise[String] = js.native\n"))
    assert(result.contains("  def removeThread(key: String, limit: js.Dynamic): js.Promise[js.Array[String]] = js.native\n"))
    assert(result.contains("  def getRemoved(): js.Promise[js.Array[String]] = js.native\n"))
    for (absent <- Seq("def read", "def scoped", "def helper", "size", "count", "def commented", "def quoted", "def nested", "override", "final"))
      assert(!result.contains(absent), absent)
  }

  test("stub names strip a DurableObject suffix and classes are sorted by export name regardless of input order") {
    def source(name: String) = s"$name.scala" -> (prelude +
      s"""@JSExportTopLevel("$name", "server")
         |class Impl$name(ctx: DurableObjectState, env: js.Any) extends DurableObject(ctx, env) { def ping(): js.Promise[String] = js.native }
         |""".stripMargin)
    val sources = Seq(source("V6PlaceholderDurableObject"), source("Thread"), source("Board"))
    val result = GenerateDurableObjectStubs.render(sources)
    assertEquals(result, GenerateDurableObjectStubs.render(sources.reverse))
    val order = Seq("trait BoardDoStub", "trait ThreadDoStub", "trait V6PlaceholderDoStub").map(result.indexOf)
    assert(order.forall(_ >= 0) && order == order.sorted, order.toString)
    assert(!result.contains("V6PlaceholderDurableObjectDoStub"))
    assert(!GenerateDurableObjectStubs.render(sources.tail).contains("V6PlaceholderDoStub"))
  }

  test("methods are emitted in name order and a renamed or removed method disappears from the next generation") {
    val before = render("  def zeta(): js.Promise[Unit] = js.native\n  def alpha(): js.Promise[Unit] = js.native")
    assert(before.indexOf("def alpha") < before.indexOf("def zeta"))
    val after = render("  def alpha(): js.Promise[Unit] = js.native")
    assert(!after.contains("zeta"))
  }

  test("defaulted parameters become js.UndefOr = js.native without copying the default or double-wrapping") {
    val result = render(
      """  def getDat(bbs: String = "", key: String = "0"): js.Promise[String] = js.native
        |  def addRes(datLine: String, posting: js.UndefOr[js.Dynamic] = js.undefined): js.Promise[Int] = js.native
        |  def update(data: js.Dynamic, sage: js.UndefOr[Boolean] = js.undefined, max: scala.scalajs.js.UndefOr[Double] = js.undefined): js.Promise[Unit] = js.native
        |""".stripMargin)
    assert(result.contains("def getDat(bbs: js.UndefOr[String] = js.native, key: js.UndefOr[String] = js.native): js.Promise[String] = js.native"))
    assert(result.contains("def addRes(datLine: String, posting: js.UndefOr[js.Dynamic] = js.native): js.Promise[Int] = js.native"))
    assert(result.contains("sage: js.UndefOr[Boolean] = js.native, max: scala.scalajs.js.UndefOr[Double] = js.native)"))
    assert(!result.contains("\"0\""))
  }

  test("facade types resolve through explicit, wildcard or fully qualified references to the cloudflare package") {
    val wildcard = render("  def inspect(): js.Promise[ThreadInspectResult] = js.native")
    assert(wildcard.contains("js.Promise[io._3ch.bbs.external.cloudflare.ThreadInspectResult]"))
    val explicit = render("  def inspect(): js.Promise[ThreadInspectResult] = js.native", header =
      "import io._3ch.bbs.external.cloudflare.{DurableObject, DurableObjectState, ThreadInspectResult}\nimport scala.scalajs.js\nimport scala.scalajs.js.annotation.JSExportTopLevel\n")
    assert(explicit.contains("js.Promise[io._3ch.bbs.external.cloudflare.ThreadInspectResult]"))
    val qualified = render("  def inspect(): scala.scalajs.js.Promise[io._3ch.bbs.external.cloudflare.ThreadInspectResult] = js.native")
    assert(qualified.contains("js.Promise[io._3ch.bbs.external.cloudflare.ThreadInspectResult]"))
  }

  test("unresolvable, aliased, foreign-package and locally declared types fail with the file and member name") {
    val missing = rejects("  def f(): js.Promise[Unknown] = js.native",
      header = "import io._3ch.bbs.external.cloudflare.{DurableObject, DurableObjectState}\nimport scala.scalajs.js\nimport scala.scalajs.js.annotation.JSExportTopLevel\n")
    assert(missing.startsWith("Example.scala: Board.f:"), missing)
    assert(missing.contains("Unknown"))
    val renamed = rejects("  def f(): js.Promise[Result] = js.native", header = prelude + "import io._3ch.bbs.external.cloudflare.{ThreadInspectResult => Result}\n")
    assert(renamed.contains("renaming import"), renamed)
    val foreign = rejects("  def f(x: ThreadCreationHistory): js.Promise[Unit] = js.native", header = prelude + "import io._3ch.bbs.domain.posting.moderation.ThreadCreationHistory\n")
    assert(foreign.contains("io._3ch.bbs.domain.posting.moderation"), foreign)
    // 複数の `*` import があるときは cloudflare パッケージ由来とみなして完全修飾名にする（他パッケージの型なら bbs のコンパイルで落ちる）
    val wildcards = render("  def f(x: Thing): js.Promise[Unit] = js.native", header = prelude + "import io._3ch.bbs.domain.*\n")
    assert(wildcards.contains("x: io._3ch.bbs.external.cloudflare.Thing"), wildcards)
    val otherWildcard = rejects("  def f(x: Thing): js.Promise[Unit] = js.native",
      header = "import io._3ch.bbs.external.cloudflare.{DurableObject, DurableObjectState}\nimport io._3ch.bbs.domain.*\nimport scala.scalajs.js\nimport scala.scalajs.js.annotation.JSExportTopLevel\n")
    assert(otherWildcard.contains("wildcard"), otherWildcard)
    val local = rejects("  def f(x: Local): js.Promise[Unit] = js.native", header = prelude + "trait Local\n")
    assert(local.contains("Local"), local)
    val alias = rejects("  def f(x: Alias): js.Promise[Unit] = js.native", header = prelude + "type Alias = String\n")
    assert(alias.contains("Alias"), alias)
    val qualified = rejects("  def f(x: io._3ch.bbs.durable.Thread): js.Promise[Unit] = js.native")
    assert(qualified.contains("io._3ch.bbs.durable.Thread"), qualified)
    val noJs = rejects("  def f(x: js.Dynamic): js.Promise[Unit] = js.native",
      header = "import io._3ch.bbs.external.cloudflare.*\nimport scala.scalajs.js.annotation.JSExportTopLevel\n")
    assert(noJs.contains("import scala.scalajs.js"), noJs)
  }

  test("declarations outside the initial scope are rejected instead of silently dropped") {
    val cases = Seq(
      "overload" -> "  def f(): js.Promise[Unit] = js.native\n  def f(x: String): js.Promise[Unit] = js.native",
      "type parameters" -> "  def f[T](x: T): js.Promise[Unit] = js.native",
      "multiple parameter lists" -> "  def f(x: String)(y: String): js.Promise[Unit] = js.native",
      "implicit / using" -> "  def f(x: String)(using y: String): js.Promise[Unit] = js.native",
      "using only" -> "  def f(using y: String): js.Promise[Unit] = js.native",
      "protected" -> "  protected def f(): js.Promise[Unit] = js.native",
      "@JSExport" -> "  @JSExport def f(): js.Promise[Unit] = js.native",
      "extension" -> "  extension (s: String) def f(): js.Promise[Unit] = js.native",
      "given" -> "  given ordering: Ordering[String] = Ordering.String",
      "nested public object" -> "  object Helpers { def helper(): js.Promise[Unit] = js.native }",
      "backquoted name" -> "  def `type`(): js.Promise[Unit] = js.native",
      "Long" -> "  def f(x: Long): js.Promise[Unit] = js.native",
      "Option" -> "  def f(): js.Promise[Option[String]] = js.native",
      "varargs" -> "  def f(xs: String*): js.Promise[Unit] = js.native",
      "by-name" -> "  def f(x: => String): js.Promise[Unit] = js.native",
      "annotated" -> "  @JSName(\"g\") def f(): js.Promise[Unit] = js.native",
      "parameterless" -> "  def f: js.Promise[Unit] = js.native",
      "return type" -> "  def f() = js.native",
      "js.Promise" -> "  def f(): String = js.native",
      "Future" -> "  def f(): scala.concurrent.Future[String] = js.native",
      "abstract" -> "  def f(): js.Promise[Unit]",
      "function type" -> "  def f(x: String => String): js.Promise[Unit] = js.native",
      "tuple type" -> "  def f(x: (String, Int)): js.Promise[Unit] = js.native",
      "inline" -> "  inline def f(): js.Promise[Unit] = js.native"
    )
    cases.foreach { case (label, body) =>
      val message = intercept[IllegalArgumentException](render(body)).getMessage
      assert(message.contains("Example.scala"), s"$label: $message")
    }
  }

  test("other modules, non-exported classes and duplicate exports behave like the TS generator") {
    val result = GenerateDurableObjectStubs.render(Seq("a.scala" -> (prelude +
      """class Helper { def leak(): js.Promise[Unit] = js.native }
        |@JSExportTopLevel("Client", "client")
        |class Client { def ping(): js.Promise[Unit] = js.native }
        |""".stripMargin)))
    assert(!result.contains("trait "))
    val source = prelude + "@JSExportTopLevel(\"Board\", \"server\")\nclass Board(state: DurableObjectState, env: js.Any) extends DurableObject(state, env)\n"
    intercept[IllegalArgumentException](GenerateDurableObjectStubs.render(Seq("a.scala" -> source, "b.scala" -> source)))
  }

  test("the real Durable Object sources generate the stubs used by the handlers") {
    val root = java.nio.file.Paths.get("bbs/src/main/scala/io/_3ch/bbs/durable")
    assume(java.nio.file.Files.isDirectory(root), "run from the repository root")
    val result = GenerateDurableObjectStubs.render(DurableObjectSources.read(root))
    assert(result.contains("trait BoardDoStub"))
    assert(result.contains("trait ThreadDoStub"))
    assert(!result.contains("V6PlaceholderDoStub"), "削除済みの DO のスタブは生成されない")
    assert(result.contains("def getDat(bbs: js.UndefOr[String] = js.native, key: js.UndefOr[String] = js.native): js.Promise[String] = js.native"))
    assert(result.contains("def inspect(bbs: js.UndefOr[String] = js.native, key: js.UndefOr[String] = js.native): js.Promise[io._3ch.bbs.external.cloudflare.ThreadInspectResult] = js.native"))
    assert(result.contains("def updateThread(data: js.Dynamic, sage: js.UndefOr[Boolean] = js.native, maxThreads: js.UndefOr[Double] = js.native): js.Promise[Unit] = js.native"))
  }
}
