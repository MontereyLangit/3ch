import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// npm の pretest（sbt generatedAppCheck）が 3ch の設定で生成した route / island
const checkDir = fileURLToPath(new URL('../target/generated-app-check/', import.meta.url));
const appDir = fileURLToPath(new URL('../app/', import.meta.url));
const marker = '// This file is generated by codegen';
const handWrittenRoutes = ['_renderer.tsx', 'admin/index.ts', 'auth.js.ts', 'bbsmenu.html.ts', 'index.ts'];

const read = (file) => readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
const files = (dir) => existsSync(dir)
  ? readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && !entry.name.endsWith('.hx4s-tmp'))
    .map((entry) => path.relative(dir, path.join(entry.parentPath, entry.name)).replaceAll('\\', '/'))
    .sort()
  : [];

for (const kind of ['routes', 'islands']) {
  test(`3ch の設定で生成した ${kind} はコミット済みの app/${kind} と一致し、生成ファイルが余っていない`, {
    skip: existsSync(path.join(checkDir, kind)) ? false : 'target/generated-app-check がありません（npm test の pretest を先に実行）',
  }, () => {
    const generated = files(path.join(checkDir, kind));
    assert.ok(generated.length > 0, `${kind} が 1 件も生成されていません`);
    const committed = files(path.join(appDir, kind)).filter((file) => read(path.join(appDir, kind, file)).startsWith(marker));
    assert.deepEqual(committed, generated);
    for (const file of generated) {
      assert.equal(read(path.join(appDir, kind, file)), read(path.join(checkDir, kind, file)), `app/${kind}/${file} が生成結果と違います`);
    }
  });
}

test('手書きの route は生成対象にならず、生成マーカーを持たない', {
  skip: existsSync(path.join(checkDir, 'routes')) ? false : 'target/generated-app-check がありません（npm test の pretest を先に実行）',
}, () => {
  const generated = files(path.join(checkDir, 'routes'));
  const handWritten = files(path.join(appDir, 'routes')).filter((file) => !read(path.join(appDir, 'routes', file)).startsWith(marker));
  assert.deepEqual(handWritten, [...handWrittenRoutes].sort());
  for (const file of handWrittenRoutes) assert.ok(!generated.includes(file), `手書きの app/routes/${file} が生成対象になっています`);
  assert.deepEqual(files(path.join(appDir, 'islands')).filter((file) => !read(path.join(appDir, 'islands', file)).startsWith(marker)), []);
});
